import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const core=read('src/js/core.js'),ui=read('src/js/approved.js'),html=read('index.html');
const val=core.slice(core.indexOf('function validateVaultPlaintext(vault) {'),core.indexOf('function buildNewVault(name) {'));
assert(val.startsWith('function validateVaultPlaintext(vault) {'));
const time='2026-10-27T14:00:00Z';
const item={id:'test-1',title:'Demo record',url:'https://example.test',username:'alice',password:'SECRET_PW_4739',notes:'SECRET_NOTE_9024',createdAt:time,updatedAt:time,kind:'login',customFields:[{label:'Private answer',value:'SECRET_CUSTOM_7301'}],tags:['office']};
const vault={schemaVersion:1,id:'vault',name:'Vault',createdAt:time,updatedAt:time,credentials:[item]};
const ctx=vm.createContext({JSON,Date,Set,Number,Object,Error,TextEncoder,secureId:()=> 'phase3-test-event',state:{vault,locked:false}});
vm.runInContext(val,ctx);
assert.equal(vm.runInContext('validateVaultPlaintext(state.vault)',ctx),true,'Old fields without a type must be accepted');
item.customFields[0].type='secret';
item.customFields.push({label:'Website',value:'https://example.test',type:'url'});
item.customFields.push({label:'Date',value:'2026-10-27',type:'date'});
item.customFields.push({label:'Label',value:'Plain label',type:'text'});
assert.equal(vm.runInContext('validateVaultPlaintext(state.vault)',ctx),true,'Typed custom fields must validate');
item.customFields[0].type='script';
assert.throws(()=>vm.runInContext('validateVaultPlaintext(state.vault)',ctx),/Invalid encrypted custom fields/,'Unexpected types must be rejected');
item.customFields[0].type='secret';
const next={...item,customFields:[{...item.customFields[0],value:'new answer'},...item.customFields.slice(1)],updatedAt:'2026-10-27T14:03:00Z'};
ctx.NEXT=next;ctx.PREVIOUS=item;
assert.equal(vm.runInContext('recordVaultHistory(PREVIOUS,NEXT,"edited")',ctx),true,'Changes to typed fields must be tracked');
assert.equal(vault.editHistory[0].after.customFields[0].value,'new answer');
assert.equal(vm.runInContext('validateVaultPlaintext(state.vault)',ctx),true,'History with typed fields must validate');
vault.editHistory[0].after.customFields[0].type='script';
assert.throws(()=>vm.runInContext('validateVaultPlaintext(state.vault)',ctx),/Invalid historical custom fields/,'Invalid historical field types must be rejected');
vault.editHistory[0].after.customFields[0].type='secret';
assert(ui.includes("const matches=getItems().filter(item=>[item.title,item.username,item.url,...(item.tags||[])]"),'Search must use non-secret metadata only');
assert(!ui.includes('innerHTML=content')&&!ui.includes('localStorage.setItem('),'New UI must not persist secret search results');
for(const id of ['pvCommandDialog','pvCommandInput','pvCommandResults','pvDetailNoteDialog','pvDetailNoteContent','pvTagSuggestions'])assert(html.includes(`id="${id}"`));
assert(ui.includes("$('pvDetailNoteContent').textContent='';"),'Note modal must clear its content');
assert(ui.includes('commandClear();detailNoteClose();'),'Vault lock must clear transient UI');
assert(ui.includes("openEditor();if($('editorDialog').open)changeKind(action.slice(7))"),'Quick creation must use existing editor');
console.log('Phase 3 tests passed: legacy compatibility, typed fields, edit history, reject unknown field types, metadata-only search, modal privacy and lock cleanup.');
